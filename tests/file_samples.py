"""Small shop files of each kind, for tests: a DXF drawing, STL and 3MF models,
and LightBurn and G-code files carrying a thumbnail."""

from __future__ import annotations

import base64
import io
import math
import struct
import zipfile

from PIL import Image


def dxf() -> bytes:
    import ezdxf

    doc = ezdxf.new()
    msp = doc.modelspace()
    msp.add_lwpolyline([(0, 0), (120, 0), (120, 40), (40, 40), (40, 90), (0, 90)], close=True)
    msp.add_circle((20, 20), 6)
    out = io.StringIO()
    doc.write(out)
    return out.getvalue().encode()


def empty_dxf() -> bytes:
    import ezdxf

    out = io.StringIO()
    ezdxf.new().write(out)
    return out.getvalue().encode()


def _ring(n: int = 24, m: int = 12) -> list:
    def p(a, b):
        u, v = 2 * math.pi * a / n, 2 * math.pi * b / m
        r = 40 + 12 * math.cos(v)
        return (r * math.cos(u), r * math.sin(u), 12 * math.sin(v))

    out = []
    for i in range(n):
        for j in range(m):
            a, b, c, d = p(i, j), p(i + 1, j), p(i + 1, j + 1), p(i, j + 1)
            out += [(a, b, c), (a, c, d)]
    return out


def stl_binary() -> bytes:
    tris = _ring()
    out = bytearray(b"\0" * 80 + struct.pack("<I", len(tris)))
    for tri in tris:
        out += struct.pack("<3f", 0, 0, 0)
        for v in tri:
            out += struct.pack("<3f", *v)
        out += b"\0\0"
    return bytes(out)


def stl_ascii() -> bytes:
    lines = ["solid ring"]
    for tri in _ring(8, 6):
        lines += ["facet normal 0 0 0", "outer loop"]
        lines += [f"vertex {x:.4f} {y:.4f} {z:.4f}" for x, y, z in tri]
        lines += ["endloop", "endfacet"]
    return "\n".join([*lines, "endsolid ring"]).encode()


def _png(color=(200, 80, 40), size=(64, 48)) -> bytes:
    out = io.BytesIO()
    Image.new("RGB", size, color).save(out, "PNG")
    return out.getvalue()


def three_mf(thumbnail: bool = False) -> bytes:
    verts, faces, index = [], [], {}
    for tri in _ring():
        ids = []
        for v in tri:
            key = tuple(round(c, 4) for c in v)
            if key not in index:
                index[key] = len(verts)
                verts.append(key)
            ids.append(index[key])
        faces.append(ids)
    model = (
        '<?xml version="1.0" encoding="UTF-8"?><model unit="millimeter" '
        'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources>'
        '<object id="1" type="model"><mesh><vertices>'
        + "".join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in verts)
        + "</vertices><triangles>"
        + "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in faces)
        + '</triangles></mesh></object></resources><build><item objectid="1"/></build></model>'
    )
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as zf:
        zf.writestr("3D/3dmodel.model", model)
        if thumbnail:
            zf.writestr(
                "_rels/.rels",
                '<?xml version="1.0"?><Relationships>'
                '<Relationship Target="/Metadata/thumbnail.png" '
                'Id="rel1" Type="http://schemas.openxmlformats.org/package/2006/relationships/'
                'metadata/thumbnail"/></Relationships>',
            )
            zf.writestr("Metadata/thumbnail.png", _png((40, 160, 90)))
    return out.getvalue()


def lightburn(thumbnail: bool = True) -> bytes:
    thumb = f'<Thumbnail Source="{base64.b64encode(_png()).decode()}"/>' if thumbnail else ""
    return (
        f'<?xml version="1.0" encoding="UTF-8"?><LightBurnProject AppVersion="1.7.03">{thumb}'
        '<CutSetting type="Cut"><index Value="0"/></CutSetting></LightBurnProject>'
    ).encode()


def gcode(thumbnail: bool = True) -> bytes:
    lines = ["; generated by PrusaSlicer 2.8.1"]
    if thumbnail:
        for size, color in (((16, 12), (0, 0, 255)), ((64, 48), (200, 80, 40))):
            data = base64.b64encode(_png(color, size)).decode()
            lines.append(f"; thumbnail begin {size[0]}x{size[1]} {len(data)}")
            lines += [f"; {data[i : i + 78]}" for i in range(0, len(data), 78)]
            lines.append("; thumbnail end")
    lines += ["G21", "G90", "G28", "G1 X10 Y10 F1200", "M104 S200", "M5"]
    return "\n".join(lines).encode()
